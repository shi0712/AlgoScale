template<class Ask> long long solve(int n,Ask ask){
    int l=0,r=n-1;long long sum=ask(l,r);
    while(r-l+1>=4){
        int lo=l,hi=r-1;
        while(lo<hi){
            int m=(lo+hi)/2;long long s=ask(l,m);
            if(s==sum/2){lo=m;break;}
            if(s<sum/2)lo=m+1;else hi=m-1;
        }
        if(lo-l+1<=r-lo)r=lo;else l=lo+1;
        sum/=2;
    }
    return l==r?sum:sum/2;
}
